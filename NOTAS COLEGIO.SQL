SELECT * FROM NOTAS;

SELECT NOMBRE_ALUMNO, ASIGNATURA, NOTA
FROM NOTAS
WHERE NOTA < 4.0;

SELECT NOMBRE_ALUMNO, NOTA
FROM NOTAS
WHERE ASIGNATURA = 'Matematicas' AND NOTA >= 5.0;

SELECT NOMBRE_ALUMNO, ASIGNATURA, NOTA
FROM NOTAS
WHERE CURSO = '3A'
ORDER BY NOTA DESC;
GO

SELECT NOMBRE_ALUMNO, AVG(NOTA) AS PROMEDIO
FROM NOTAS
GROUP BY NOMBRE_ALUMNO;

SELECT ASIGNATURA, AVG(NOTA) AS PROMEDIO_ASIGNATURA
FROM NOTAS
GROUP BY ASIGNATURA;

SELECT CURSO, AVG(NOTA) AS PROMEDIO_CURSO
FROM NOTAS
GROUP BY CURSO;
GO

