CREATE TABLE NOTAS
(
    ID_NOTA INT PRIMARY KEY IDENTITY(1,1) NOT NULL,
    NOMBRE_ALUMNO VARCHAR(100) NOT NULL,
    CURSO VARCHAR(20) NOT NULL,
    ASIGNATURA VARCHAR(60) NOT NULL,
    NOTA DECIMAL(2,1) NOT NULL
);
GO

