SELECT * FROM EMPLEADOS;

SELECT NOMBRE, APELLIDO, SALARIO
FROM EMPLEADOS
WHERE SALARIO > 1000000;

SELECT NOMBRE, DEPARTAMENTO, CIUDAD
FROM EMPLEADOS
WHERE DEPARTAMENTO = 'TI' AND CIUDAD = 'Santiago';

SELECT NOMBRE, CIUDAD
FROM EMPLEADOS
WHERE CIUDAD = 'Valparaiso' OR CIUDAD = 'Concepcion';

SELECT NOMBRE, SALARIO
FROM EMPLEADOS
ORDER BY SALARIO DESC;
GO

SELECT AVG(SALARIO) AS PROMEDIO_SALARIOS
FROM EMPLEADOS;

SELECT DEPARTAMENTO, AVG(SALARIO) AS PROMEDIO_SALARIO
FROM EMPLEADOS
GROUP BY DEPARTAMENTO;

SELECT CIUDAD, COUNT(*) AS CANTIDAD_EMPLEADOS
FROM EMPLEADOS
GROUP BY CIUDAD;

SELECT DEPARTAMENTO, MAX(SALARIO) AS SALARIO_MAS_ALTO, MIN(SALARIO) AS SALARIO_MAS_BAJO
FROM EMPLEADOS
GROUP BY DEPARTAMENTO;
GO

