CREATE TABLE USUARIOS(
    ID_USUARIO INT PRIMARY KEY IDENTITY(1,1) NOT NULL,
    NOMBRE_USUARIO VARCHAR(100) NOT NULL,
    APELLIDO_USUARIO VARCHAR(100) NOT NULL,
    CORREO_USUARIO VARCHAR(100) NOT NULL,
    TELEFONO_USUARIO VARCHAR(100) NOT NULL
);
GO

CREATE TABLE AUTORES(
    ID_AUTOR INT PRIMARY KEY IDENTITY(1,1) NOT NULL,
    NOMBRE_AUTOR VARCHAR(50) NOT NULL,
    APELLIDO_AUTOR VARCHAR(50) NOT NULL,
    NACIONALIDAD VARCHAR(50)
);
GO

CREATE TABLE LIBROS(
    ID_LIBRO INT PRIMARY KEY IDENTITY(1,1) NOT NULL,
    ID_AUTOR INT NOT NULL,
    TITULO_LIBRO VARCHAR(50) NOT NULL,
    GENERO_LIBRO VARCHAR(50),
    FECHA_PUBLICACION DATE,
    STOCK INT
);
GO

CREATE TABLE PRESTAMOS(
    ID_PRESTAMO INT PRIMARY KEY IDENTITY(1,1) NOT NULL,
    ID_USUARIO INT NOT NULL,
    ID_LIBRO INT NOT NULL,
    FECHA_PRESTAMO DATE NOT NULL,
    FECHA_DEVOLUCION DATE NULL,
    ESTADO VARCHAR(100)
);
GO

ALTER TABLE LIBROS ADD CONSTRAINT FK_LIBROS_AUTORES FOREIGN KEY (ID_AUTOR) REFERENCES AUTORES(ID_AUTOR);
GO

ALTER TABLE PRESTAMOS ADD CONSTRAINT FK_PRESTAMOS_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO);
GO

ALTER TABLE PRESTAMOS ADD CONSTRAINT FK_PRESTAMOS_LIBROS FOREIGN KEY (ID_LIBRO) REFERENCES LIBROS(ID_LIBRO);
GO

